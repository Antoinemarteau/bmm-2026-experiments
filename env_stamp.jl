# Record the machine and software environment the contents of results/ were
# produced on.
#
# Run from the repository root, under the experiment project:
#
#   julia --project=. env_stamp.jl          # covers a full re-run
#   julia --project=. env_stamp.jl 2,6      # covers a re-run of experiments 2 and 6 only
#
# Outputs: results/environment.md (read by humans, cited by the generated
# tables) and results/environment.json (same facts, machine-readable).
#
# The timings in exp2_table.md and the walltimes in the JSON records are only
# interpretable next to the machine that produced them, so this file is part of
# the results, not of the tooling: run_all.sh writes it before the first
# experiment and appends its run log to it afterwards.
#
# Every probe is individually guarded: a missing or renamed introspection API
# must degrade one field to "unknown", never abort a multi-hour run.

using LinearAlgebra
using Pkg

probe(f, fallback = "unknown") = try
  something(f(), fallback)
catch
  fallback
end

const ROOT   = @__DIR__
const RESDIR = joinpath(ROOT, "results")

git(args...) = probe() do
  s = read(Cmd(`git $(collect(args))`; dir = ROOT), String)
  isempty(strip(s)) ? nothing : strip(s)
end

# Version and origin (registry release vs local checkout) of a direct dependency.
function dep_info(name::AbstractString)
  probe(() -> begin
    for (_, p) in Pkg.dependencies()
      p.name == name || continue
      origin = p.is_tracking_path ? "local checkout at $(p.source)" :
               p.is_tracking_repo ? "git checkout $(p.source)" : "registry release"
      return (version = string(p.version), origin = origin)
    end
    nothing
  end, (version = "unknown", origin = "unknown"))
end

cpu_model() = probe(() -> strip(first(Sys.cpu_info()).model))

memory_gib() = probe(() -> string(round(Sys.total_memory() / 2^30, digits = 1), " GiB"))

blas_vendor() = probe(() -> join([b.libname for b in LinearAlgebra.BLAS.get_config().loaded_libs], ", "))
blas_threads() = probe(() -> string(LinearAlgebra.BLAS.get_num_threads()))

# julia_version recorded in the committed Manifest. It is rewritten by
# Pkg.instantiate() under a different Julia, so a mismatch with VERSION means
# the Manifest needs re-committing alongside the results.
manifest_julia() = probe(() -> begin
  for line in eachline(joinpath(ROOT, "Manifest.toml"))
    m = match(r"^julia_version\s*=\s*\"([^\"]+)\"", line)
    m === nothing || return m.captures[1]
  end
  nothing
end)

pkg_status() = probe(() -> sprint(io -> Pkg.status(; io = io)))

const GRIDAP = dep_info("Gridap")

const FACTS = [
  "recorded"        => probe(() -> Libc.strftime("%Y-%m-%d %H:%M:%S %Z", time())),
  "hostname"        => probe(gethostname),
  "julia_version"   => string(VERSION),
  "manifest_julia"  => manifest_julia(),
  "gridap_version"  => GRIDAP.version,
  "gridap_origin"   => GRIDAP.origin,
  "machine_triple"  => Sys.MACHINE,
  "cpu_model"       => cpu_model(),
  "cpu_target"      => Sys.CPU_NAME,
  "cpu_threads"     => string(Sys.CPU_THREADS),
  "total_memory"    => memory_gib(),
  "julia_threads"   => string(Threads.nthreads()),
  "blas_library"    => blas_vendor(),
  "blas_threads"    => blas_threads(),
  "git_commit"      => git("rev-parse", "HEAD"),
  "git_describe"    => git("describe", "--always", "--dirty"),
  "git_dirty"       => probe(() -> isempty(strip(read(Cmd(`git status --porcelain`; dir = ROOT),
                                                         String))) ? "no" : "yes"),
]

json_str(s) = "\"" * replace(string(s), "\\" => "\\\\", "\"" => "\\\"", "\n" => "\\n") * "\""

function main()
  mkpath(RESDIR)

  # A restriction passed by run_all.sh --only: the stamp then describes the
  # experiments it covers, not the whole directory.
  covers = isempty(ARGS) ? "" : join(ARGS, " ")

  open(joinpath(RESDIR, "environment.json"), "w") do io
    print(io, "{", join([json_str(k) * ":" * json_str(v) for (k, v) in FACTS], ","), "}\n")
  end

  d = Dict(FACTS)
  open(joinpath(RESDIR, "environment.md"), "w") do io
    println(io, "# Environment of the results in this directory\n")
    println(io, "Written by `env_stamp.jl`; regenerated by `run_all.sh` on every re-run.")
    println(io, "The timings in `exp2_table.md` and the `walltime_s` fields of the JSON")
    println(io, "records are specific to this machine.\n")
    if !isempty(covers)
      println(io, "**Covers experiments ", covers, " only.** The remaining files in this")
      println(io, "directory were produced by an earlier run, on a possibly different")
      println(io, "machine; see the run log below.\n")
    end
    println(io, "| field | value |")
    println(io, "|---|---|")
    for (k, v) in FACTS
      println(io, "| `", k, "` | ", replace(string(v), "|" => "\\|"), " |")
    end
    println(io)
    if d["manifest_julia"] != string(VERSION)
      println(io, "> `Manifest.toml` records `julia_version = \"", d["manifest_julia"],
                  "\"` but these results were produced on Julia ", VERSION,
                  ". Commit the regenerated `Manifest.toml` with the results.\n")
    end
    println(io, "## Resolved environment\n")
    println(io, "```")
    print(io, pkg_status())
    println(io, "```")
  end

  println("wrote ", joinpath(RESDIR, "environment.md"), " and environment.json")
  println("  Julia ", VERSION, " | Gridap ", d["gridap_version"], " (", d["gridap_origin"], ")")
  println("  ", d["cpu_model"], " | ", d["cpu_threads"], " logical cores | ",
          d["julia_threads"], " Julia thread(s) | ", d["blas_threads"], " BLAS thread(s)")
end

main()
